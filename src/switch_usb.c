const uint8_t *switch_usb_hid_descriptor(uint16_t *len)
{
    if (len) *len = sizeof(report_desc);
    return report_desc;
}

const uint8_t *switch_usb_config_descriptor(bool mic, bool high_speed,
                                           bool other_speed, uint16_t *len)
{
    static uint8_t config[sizeof(base_config) + sizeof(mic_desc)];
    uint16_t n = sizeof(base_config);
    memcpy(config, base_config, n);
    if (mic) { memcpy(config+n, mic_desc, sizeof(mic_desc)); n += sizeof(mic_desc); }
    config[1] = other_speed ? 7 : 2;
    config[2] = (uint8_t)n; config[3] = (uint8_t)(n >> 8);
    config[4] = mic ? 3 : 1;
    for (unsigned i = 9; i < n; i += config[i]) {
        if (config[i+1] == 5) {
            config[i+6] = config[i+2] == SWITCH_USB_MIC_EP ?
                (high_speed ? 4 : 1) : (high_speed ? 7 : 8);
        }
    }
    if (len) *len = n;
    return config;
}
